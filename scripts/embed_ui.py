"""Embed offline appliance assets into the build directory, without SD/CDNs."""
from pathlib import Path


def generate(root: Path, output: Path):
    assets = (("applianceHtml", "index.html"), ("applianceCss", "style.css"),
              ("applianceJs", "app.js"), ("applianceI18n", "i18n.js"))
    parts = ["// Generated by scripts/embed_ui.py. Edit ui/appliance instead.\n#pragma once\n"]
    for symbol, filename in assets:
        text = (root / "ui/appliance" / filename).read_text(encoding="utf-8")
        if ')UI_ASSET"' in text:
            raise ValueError("Asset contains the C++ raw string delimiter")
        parts.append(f'static const char {symbol}[] = R"UI_ASSET({text})UI_ASSET";\n')
    output.parent.mkdir(parents=True, exist_ok=True)
    content = "".join(parts)
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8", newline="\n")


try:
    Import("env")  # PlatformIO/SCons
except NameError:
    if __name__ == "__main__":
        import argparse
        parser = argparse.ArgumentParser(description=__doc__)
        parser.add_argument("--out", type=Path, required=True)
        args = parser.parse_args()
        generate(Path(__file__).resolve().parents[1], args.out)
else:
    generated = Path(env.subst("$BUILD_DIR")) / "generated"
    generate(Path(env.subst("$PROJECT_DIR")), generated / "applianceAssets.h")
    env.Append(CPPPATH=[str(generated)])
